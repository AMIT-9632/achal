"""Packet-delivery study for the simulated LoRa mesh.

Runs every site x radio profile x mode (mesh / single-hop star) x failure fraction
over several seeds, with the failed nodes dying without warning one hour in, and
writes a JSON report plus a Markdown table:

    python services/field-sim/src/mesh_study.py --seeds 10 --hours 6

PDR counts readings from live nodes only: a dead node has nothing to deliver,
but a live node cut off by dead relays counts as a loss.
"""

from __future__ import annotations

import argparse
import json
import statistics
from concurrent.futures import ProcessPoolExecutor
from dataclasses import asdict
from datetime import UTC, datetime, timedelta
from pathlib import Path

from achal_common import Telemetry, load_site
from mesh import PROFILES, Mesh

FAIL_FRACTIONS = (0.0, 0.1, 0.2, 0.3)
MODES = ("mesh", "star")
PATTERNS = ("random", "cluster")
REPO = Path(__file__).resolve().parents[3]


def run_one(site_id: str, profile: str, mode: str, pattern: str, fail: float, seed: int, hours: float) -> dict:
    site = load_site(site_id)
    mesh = Mesh(site, PROFILES[profile], seed=seed, fail_fraction=fail, fail_at_s=3600, mode=mode,
                fail_pattern=pattern)
    mesh.with_neighbour_rssi = False  # not needed for delivery counts, and slow
    t0 = datetime(2026, 10, 21, tzinfo=UTC)
    period = site.mesh.sample_period_s
    for k in range(int(hours * 3600 / period)):
        ts = t0 + timedelta(seconds=k * period)
        for node in site.node_ids():
            mesh.transmit(Telemetry(site=site_id, node=node, seq=k, ts=ts, tilt_x_deg=0, tilt_y_deg=0,
                                    vib_rms_g=0, crack_mm=0, ext_mm=0, batt_v=3.9))
    out = mesh.stats.summary()
    out["relays"] = sum(1 for n in site.node_ids() if mesh.hops_to_gw.get(n, 0) > 1)
    out["unreachable_at_start"] = sum(1 for n in site.node_ids() if n not in mesh.hops_to_gw)
    out["airtime_s_per_node_day"] = round(out["airtime_s"] / len(site.node_ids()) * 24 / hours, 2)
    return {"site": site_id, "profile": profile, "mode": mode, "pattern": pattern, "fail": fail, "seed": seed, **out}


def aggregate(runs: list[dict]) -> list[dict]:
    groups: dict[tuple, list[dict]] = {}
    for r in runs:
        groups.setdefault((r["site"], r["profile"], r["pattern"], r["mode"], r["fail"]), []).append(r)
    rows = []
    for (site, profile, pattern, mode, fail), rs in sorted(groups.items()):
        pdrs = [r["pdr"] for r in rs]
        rows.append({
            "site": site, "profile": profile, "pattern": pattern, "mode": mode, "fail": fail, "runs": len(rs),
            "pdr_mean": round(statistics.fmean(pdrs), 5), "pdr_min": round(min(pdrs), 5),
            "worst_node_pdr": round(min(r["worst_node_pdr"] or 0 for r in rs), 4),
            "duplicate_rate": round(sum(r["duplicates"] for r in rs) / max(1, sum(r["delivered"] for r in rs)), 4),
            "mean_hops": round(statistics.fmean(r["mean_hops"] or 0 for r in rs), 2),
            "latency_p95_s": round(statistics.fmean(r["latency_p95_s"] or 0 for r in rs), 2),
            "local_repairs": round(statistics.fmean(r["local_repairs"] for r in rs), 1),
            "airtime_s_per_node_day": round(statistics.fmean(r["airtime_s_per_node_day"] for r in rs), 1),
        })
    return rows


def markdown(rows: list[dict], args: argparse.Namespace) -> str:
    lines = [
        "# Mesh packet-delivery study (synthetic)",
        "",
        f"Generated by `python services/field-sim/src/mesh_study.py --seeds {args.seeds} --hours {args.hours}` "
        f"on {datetime.now(UTC).date().isoformat()}. Each row is the mean over {args.seeds} seeds. Failed nodes die "
        "without warning 1 h into the run, either at random or as one contiguous patch (`cluster`, e.g. "
        "a pothole); PDR counts readings from live nodes only. `star` is the "
        "single-hop LoRaWAN-style baseline with per-node spreading factor (ADR-like). Model and "
        "assumptions: [mesh.md](mesh.md).",
        "",
        "| Site | Radio profile | Failures | Mode | Nodes down | PDR mean | PDR worst run | Worst node PDR "
        "| Duplicates | Mean hops | p95 latency (s) | Local repairs / run | Airtime / node / day (s) |",
        "| --- | --- | --- | --- | --- | --- | --- | --- | --- | --- | --- | --- | --- |",
    ]
    for r in rows:
        lines.append(
            f"| {r['site']} | {r['profile']} | {r['pattern']} | {r['mode']} | {r['fail']:.0%} | {r['pdr_mean']:.3%} | "
            f"{r['pdr_min']:.3%} | {r['worst_node_pdr']:.1%} | {r['duplicate_rate']:.1%} | {r['mean_hops']} | "
            f"{r['latency_p95_s']} | {r['local_repairs']} | {r['airtime_s_per_node_day']} |")
    lines += ["", "Raw per-run numbers: `data/mesh-study/results.json`.", ""]
    return "\n".join(lines)


def main() -> None:
    p = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    p.add_argument("--sites", nargs="+", default=["jharia-demo", "jharia-colliery"])
    p.add_argument("--profiles", nargs="+", default=list(PROFILES))
    p.add_argument("--seeds", type=int, default=10)
    p.add_argument("--hours", type=float, default=6)
    p.add_argument("--out", type=Path, default=REPO / "data" / "mesh-study" / "results.json")
    p.add_argument("--md", type=Path, default=REPO / "docs" / "mesh-study.md")
    args = p.parse_args()

    jobs = [(s, pr, m, pat, f, seed, args.hours) for s in args.sites for pr in args.profiles for m in MODES
            for pat in PATTERNS for f in FAIL_FRACTIONS for seed in range(1, args.seeds + 1)
            if not (f == 0 and pat == "cluster")]
    with ProcessPoolExecutor() as pool:
        runs = list(pool.map(run_one, *zip(*jobs, strict=True)))
    rows = aggregate(runs)
    args.out.parent.mkdir(parents=True, exist_ok=True)
    args.out.write_text(json.dumps({
        "generated": datetime.now(UTC).isoformat(), "synthetic": True, "seeds": args.seeds, "hours": args.hours,
        "fail_at_s": 3600, "profiles": {k: asdict(v) for k, v in PROFILES.items() if k in args.profiles},
        "summary": rows, "runs": runs}, indent=1))
    args.md.write_text(markdown(rows, args), encoding="utf-8")
    print(markdown(rows, args))


if __name__ == "__main__":
    main()
