"""Energy budget of one ACHAL node per sample period, from datasheet currents.

    python hardware/power_budget.py        # prints and rewrites hardware/power-budget.md

The timeline follows firmware/src/node-esp32/main.cpp and the timing constants
in firmware/lib/achal_mesh/achal_mesh.h. Currents are datasheet typicals (see
CURRENT_MA); they must be checked against a bench measurement of the first
prototype before any battery-life figure is quoted as measured.
"""

from __future__ import annotations

import math
from dataclasses import dataclass
from pathlib import Path

HERE = Path(__file__).resolve().parent

# Datasheet currents in mA.
CURRENT_MA = {
    "esp32_active_80mhz": 31.0,   # ESP32 datasheet v4, modem-sleep at 80 MHz, upper bound (Wi-Fi/BT off)
    "esp32_light_sleep": 0.8,     # ESP32 datasheet, light-sleep
    "esp32_deep_sleep": 0.010,    # ESP32 datasheet, deep-sleep with RTC timer + RTC memory
    "sx1276_rx": 11.5,            # SX1276 datasheet rev 7, RX LnaBoost on, BW 125 kHz, band 1
    "sx1276_tx_17dbm": 87.0,      # SX1276 datasheet, PA_BOOST +17 dBm
    "sx1276_sleep": 0.0002,
    "mpu6050_on": 0.5,            # MPU-6050 datasheet, accelerometer only
    "mpu6050_cycle_5hz": 0.020,   # MPU-6050 datasheet, low-power accelerometer at 5 Hz (motion wake armed)
    "ads1115_on": 0.15,           # ADS1115 datasheet, continuous conversion
    "pots_and_ntc": 0.83,         # 2 x 10k pots + 20k NTC divider across 3.3 V, only while sampling
    "vl53l0x_ranging": 19.0,      # VL53L0X datasheet, active ranging average
    "vl53l0x_standby": 0.005,     # VL53L0X datasheet, hardware standby (XSHUT low)
    "ht7333_iq": 0.004,           # HT73xx datasheet quiescent current
    "devkit_usb_uart": 0.10,      # USB-UART bridge on the dev board: assumption, measure; 0 on the production PCB
}

# Firmware timing (achal_mesh.h, main.cpp, board.h).
SAMPLE_S = 2.6
TOF_SHOTS, TOF_BUDGET_S = 7, 0.2  # VL53L0X high-accuracy mode, one 7-shot burst per period
GUARD_S = 0.3
BEACON_PHASE_S = 2.0
SLOT_S = 0.25
SF, BW_HZ, CR, PREAMBLE = 7, 125_000, 5, 8
BEACON_BYTES, TELEMETRY_BYTES = 20, 51


def lora_airtime_s(payload: int, sf: int = SF, bw_hz: int = BW_HZ, cr: int = CR, preamble: int = PREAMBLE) -> float:
    """Semtech AN1200.13, explicit header, CRC on. Mirrors achal::lora_airtime_ms."""
    t_sym = (1 << sf) / bw_hz
    de = 1 if t_sym > 0.016 else 0
    n_payload = 8 + max(math.ceil((8 * payload - 4 * sf + 28 + 16) / (4 * (sf - 2 * de))) * cr, 0)
    return (preamble + 4.25 + n_payload) * t_sym


@dataclass
class Budget:
    role: str
    period_s: int
    mah_per_period: float

    @property
    def avg_ma(self) -> float:
        return self.mah_per_period * 3600 / self.period_s

    @property
    def mah_per_day(self) -> float:
        return self.avg_ma * 24


def period_budget(role: str, period_s: int, n_nodes: int = 25, node_id: int = 13, children: int = 3,
                  prototype: bool = True) -> Budget:
    """mAh drawn in one period by a leaf node or a relay node with `children` children."""
    c = CURRENT_MA
    awake = c["esp32_active_80mhz"]
    rx = awake + c["sx1276_rx"]
    tx = awake + c["sx1276_tx_17dbm"]
    sensors = c["mpu6050_on"] + c["ads1115_on"] + c["pots_and_ntc"]
    t_beacon, t_tel = lora_airtime_s(BEACON_BYTES), lora_airtime_s(TELEMETRY_BYTES)
    ack_wait = 2 * t_tel + 0.2

    phases = [  # (seconds, mA)
        (SAMPLE_S, awake + sensors),
        (TOF_SHOTS * TOF_BUDGET_S, awake + c["vl53l0x_ranging"]),
        (GUARD_S + BEACON_PHASE_S, rx),
        (t_beacon, tx),            # relay the beacon once
        (t_tel, tx),               # own reading
        (ack_wait, rx),
    ]
    if role == "leaf":
        phases.append(((node_id - 1) * SLOT_S, c["esp32_light_sleep"]))  # doze until our slot
    elif role == "relay":
        window = 2 * n_nodes * SLOT_S
        phases.append((window - t_tel - ack_wait - children * t_tel, rx))  # listen for the whole data window
        phases.append((children * t_tel, tx))                              # forward each child's frame
    else:
        raise ValueError(role)

    busy = sum(t for t, _ in phases)
    sleep_ma = (c["esp32_deep_sleep"] + c["mpu6050_cycle_5hz"] + c["ht7333_iq"] + c["sx1276_sleep"]
                + c["vl53l0x_standby"]
                + (c["devkit_usb_uart"] if prototype else 0))
    phases.append((period_s - busy, sleep_ma))
    return Budget(role, period_s, sum(t * ma for t, ma in phases) / 3600)


# Battery and solar assumptions.
CELL_MAH, USABLE = 3000, 0.8
PANEL_W, PEAK_SUN_H, SOLAR_DERATE, CELL_V = 2.0, 4.0, 0.5, 3.7


def autonomy_days(b: Budget) -> float:
    return CELL_MAH * USABLE / b.mah_per_day


def solar_mah_per_day() -> float:
    return PANEL_W * PEAK_SUN_H * SOLAR_DERATE / CELL_V * 1000


def report() -> str:
    out = ["# Node power budget (generated by `hardware/power_budget.py`, do not edit)", "",
           "Datasheet typical currents, firmware timing as written. **Calculated, not measured**: "
           "replace with bench numbers from the first prototype.", "",
           f"LoRa airtime at SF{SF}/125 kHz/CR 4/{CR}: beacon {lora_airtime_s(BEACON_BYTES) * 1000:.0f} ms, "
           f"telemetry {lora_airtime_s(TELEMETRY_BYTES) * 1000:.0f} ms.", "",
           "| Role | Period | Average current | Per day | Days on battery alone | Solar margin |",
           "| --- | --- | --- | --- | --- | --- |"]
    for period in (60, 300):
        for role in ("leaf", "relay"):
            b = period_budget(role, period)
            margin = solar_mah_per_day() / b.mah_per_day
            out.append(f"| {role} | {period} s | {b.avg_ma:.2f} mA | {b.mah_per_day:.0f} mAh | "
                       f"{autonomy_days(b):.0f} | {margin:.1f}× |")
    prod = period_budget("relay", 60, prototype=False)
    out += ["",
            f"Battery: one {CELL_MAH} mAh 18650, {USABLE:.0%} usable. Solar: {PANEL_W:g} W panel × "
            f"{PEAK_SUN_H:g} peak-sun hours × {SOLAR_DERATE:.0%} derating (charger, angle, dust) "
            f"= {solar_mah_per_day():.0f} mAh/day at {CELL_V} V. Margin = solar in / node use per day.",
            "",
            f"Production PCB without the USB-UART bridge, relay at 60 s: {prod.avg_ma:.2f} mA.",
            "",
            "The radio window dominates: a relay listens for the whole data window "
            f"({2 * 25 * SLOT_S:.1f} s per period at 25 nodes), a leaf only for the beacon and its ack. "
            "Next optimisation: per-hop-ring slots so relays only listen while their children transmit.", ""]
    return "\n".join(out)


def main() -> None:
    md = report()
    (HERE / "power-budget.md").write_text(md)
    print(md)


if __name__ == "__main__":
    main()
