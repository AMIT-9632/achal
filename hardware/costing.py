"""Per-node and per-site cost from hardware/bom.csv.

    python hardware/costing.py            # prints the summary and rewrites hardware/cost-summary.md

All totals include 18% GST. Rows marked `estimate` have no supplier quote yet;
the summary says how much of each total they make up.
"""

from __future__ import annotations

import csv
from dataclasses import dataclass
from pathlib import Path

HERE = Path(__file__).resolve().parent
GST = 0.18

# Comparators, quoted with their source (see docs/related-work.md).
RONALD_REX_NODE = 4850  # github.com/RONALD-REX-7/sih26025 hardware/bom/BOM.md (estimated, not quoted)
IMPORTED_STATION = (150_000, 450_000)  # same repo, presentation/SIH26025_PITCH_BRIEF.md


@dataclass
class Line:
    kit: str
    item: str
    qty: int
    unit_inr: float
    gst: str
    basis: str
    source: str

    @property
    def total_incl_gst(self) -> float:
        unit = self.unit_inr * (1 + GST) if self.gst == "ex" else self.unit_inr
        return unit * self.qty


def load(path: Path = HERE / "bom.csv") -> list[Line]:
    with path.open(newline="") as f:
        return [Line(r["kit"], r["item"], int(r["qty"]), float(r["unit_inr"]), r["gst"], r["basis"], r["source"])
                for r in csv.DictReader(f)]


def kit_cost(lines: list[Line], kit: str) -> tuple[float, float]:
    """(total incl. GST, part of it that is still an estimate)."""
    rows = [x for x in lines if x.kit == kit]
    if not rows:
        raise ValueError(f"no BOM rows for kit {kit!r}")
    total = sum(x.total_incl_gst for x in rows)
    est = sum(x.total_incl_gst for x in rows if x.basis == "estimate")
    return total, est


@dataclass
class SiteCost:
    nodes: int
    sirens: int
    node: float
    gateway: float
    siren: float
    area_ha: float
    people: int

    @property
    def total(self) -> float:
        return self.nodes * self.node + self.gateway + self.sirens * self.siren

    @property
    def per_ha(self) -> float:
        return self.total / self.area_ha

    @property
    def per_person(self) -> float:
        return self.total / self.people


def site_cost(lines: list[Line], nodes: int, sirens: int, area_m2: float, people: int) -> SiteCost:
    return SiteCost(nodes, sirens, kit_cost(lines, "node")[0], kit_cost(lines, "gateway")[0],
                    kit_cost(lines, "siren")[0], area_m2 / 10_000, people)


def rupees(x: float) -> str:
    """Indian digit grouping: 113271 -> ₹1,13,271."""
    digits = f"{round(x):d}"
    head, tail = digits[:-3], digits[-3:]
    groups = []
    while len(head) > 2:
        groups.insert(0, head[-2:])
        head = head[:-2]
    if head:
        groups.insert(0, head)
    return "₹" + ",".join(groups + [tail])


def summary_md(lines: list[Line], site_id: str, sc: SiteCost) -> str:
    out = ["# Cost summary (generated by `hardware/costing.py`, do not edit)", "",
           "Retail prices for single units, 18% GST included. Bulk orders will be lower.", "",
           "| Kit | Cost | Of which still estimated |", "| --- | --- | --- |"]
    for kit in ("node", "gateway", "siren"):
        total, est = kit_cost(lines, kit)
        out.append(f"| {kit} | {rupees(total)} | {rupees(est)} ({est / total:.0%}) |")
    out += ["", f"## One panel kit: `{site_id}`", "",
            "| | |", "| --- | --- |",
            f"| Nodes | {sc.nodes} × {rupees(sc.node)} |",
            f"| Gateway | 1 × {rupees(sc.gateway)} |",
            f"| Sirens | {sc.sirens} × {rupees(sc.siren)} |",
            f"| **Total** | **{rupees(sc.total)}** |",
            f"| Area covered | {sc.area_ha:.2f} ha |",
            f"| Cost per hectare | {rupees(sc.per_ha)} |",
            f"| People protected (site config) | {sc.people} |",
            f"| Cost per person protected | {rupees(sc.per_person)} |",
            "", "## Per-node comparison", "",
            "| Option | Cost per monitoring point | Note |", "| --- | --- | --- |",
            f"| ACHAL surface node | {rupees(sc.node)} | Tilt, vibration, crack, extensometer, ground temperature, "
            "mesh relay; every quoted line has a supplier link |",
            f"| RONALD-REX-7/sih26025 node | {rupees(RONALD_REX_NODE)} | Underground rock-bolt strain node; "
            "their own estimate |",
            f"| Imported monitoring station | {rupees(IMPORTED_STATION[0])}–{rupees(IMPORTED_STATION[1])} | "
            "As cited by RONALD-REX-7/sih26025 |",
            "", f"ACHAL node vs imported station: {IMPORTED_STATION[0] / sc.node:.0f}×–"
            f"{IMPORTED_STATION[1] / sc.node:.0f}× cheaper per monitoring point.", ""]
    return "\n".join(out)


def main() -> None:
    from achal_common import load_site

    site = load_site()
    lines = load()
    sc = site_cost(lines, len(site.node_ids()), len(site.sirens),
                   site.panel.width_m * site.panel.length_m, site.exposure.people)
    md = summary_md(lines, site.site_id, sc)
    (HERE / "cost-summary.md").write_text(md)
    print(md)


if __name__ == "__main__":
    main()
